export function expressItinerary(locale: Locale, siteId: string, direction: string) {
  const site = expressSites.find((item) => item.id === siteId) ?? expressSites[0];
  const airport = experienceCopy[locale].airport;
  return direction === "to-airport" ? { from: site[locale], to: airport } : { from: airport, to: site[locale] };
}
