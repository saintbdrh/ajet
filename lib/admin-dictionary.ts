export function cmsSectionText(locale: Locale, section: string): string {
  return cmsSections[locale][section as keyof typeof cmsSections.mn] ?? section;
}

export function cmsFieldText(locale: Locale, key: string, fallback: string): string {
  const field = cmsLabels[locale] as Record<string, string>;
  if (field[key]) return field[key];
  const scene = /^journey(\d+)(Label|Title|Body)$/.exec(key);
  if (!scene) return fallback;
  const sceneNumber = scene[1];
  const part = scene[2] === "Label" ? "Хэсгийн нэр" : scene[2] === "Title" ? "Гарчиг" : "Тайлбар";
  return locale === "mn" ? `Аяллын ${sceneNumber} · ${part}` : `Journey ${sceneNumber} · ${scene[2]}`;
}
